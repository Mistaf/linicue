"""Generate linicue/evcodes.py from the kernel's input-event-codes.h.

Usage: python3 tools/gen_evcodes.py [/usr/include/linux/input-event-codes.h]
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h"
consts = {}
for line in open(src):
    m = re.match(r"#define\s+((?:KEY|BTN|REL|EV|SYN)_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+|\(?[A-Z_0-9+ ]+\)?)\s*(?:/\*.*)?$", line)
    if m:
        consts[m.group(1)] = m.group(2).strip()

def ev(name, seen=()):
    v = consts[name].strip("()")
    if re.fullmatch(r"0x[0-9a-fA-F]+|\d+", v):
        return int(v, 0)
    return sum(ev(t.strip(), seen + (name,)) if not t.strip().isdigit() else int(t) for t in v.split("+"))

out = ['"""Linux input event codes. Generated by tools/gen_evcodes.py - do not edit."""', ""]
for name in sorted(consts):
    try:
        out.append(f"{name} = {ev(name)}")
    except (KeyError, RecursionError):
        pass
open("linicue/evcodes.py", "w").write("\n".join(out) + "\n")
print(f"wrote {len(out) - 2} constants")
